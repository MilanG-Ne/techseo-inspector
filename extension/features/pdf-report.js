export function generatePdf(auditData, scoreResults, moduleConfig) {
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF('p', 'mm', 'a4');
  const pageWidth = 210;
  const pageHeight = 297;
  const margin = 20;
  const contentWidth = pageWidth - 2 * margin;
  let y = margin;

  function checkPageBreak(needed) {
    if (y + needed > pageHeight - margin) {
      doc.addPage();
      y = margin;
      return true;
    }
    return false;
  }

  function drawLine() {
    doc.setDrawColor(229, 231, 235);
    doc.line(margin, y, pageWidth - margin, y);
    y += 4;
  }

  function sectionTitle(text) {
    checkPageBreak(20);
    y += 4;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(107, 114, 128);
    doc.text(text.toUpperCase(), margin, y);
    y += 6;
  }

  // Cover
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(31, 41, 55);
  doc.text('iviG', margin, y);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(45, 127, 249);
  doc.text(' Technical SEO', margin + doc.getTextWidth('iviG') + 2, y);
  y += 12;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(31, 41, 55);
  doc.text('TechSEO Inspector', margin, y);
  y += 8;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(107, 114, 128);
  doc.text('SEO Audit Report', margin, y);
  y += 12;

  drawLine();

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(107, 114, 128);
  doc.text(`URL: ${truncateStr(auditData.pageUrl, 80)}`, margin, y);
  y += 5;
  doc.text(`Date: ${new Date(auditData.timestamp).toLocaleString()}`, margin, y);
  y += 10;

  // Overall Score
  const score = scoreResults.totalScore;
  const scoreColor = score >= 80 ? [34, 197, 94] : score >= 50 ? [245, 158, 11] : [239, 68, 68];

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(48);
  doc.setTextColor(...scoreColor);
  doc.text(`${score}`, margin, y + 16);
  const scoreWidth = doc.getTextWidth(`${score}`);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(16);
  doc.setTextColor(156, 163, 175);
  doc.text('/ 100', margin + scoreWidth + 3, y + 16);
  y += 24;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(107, 114, 128);
  doc.text('Overall SEO Score', margin, y);
  y += 12;

  drawLine();

  // Module score bars
  sectionTitle('Module Scores');

  moduleConfig.forEach(({ key, name }) => {
    const mod = scoreResults.modules[key];
    if (!mod) return;
    checkPageBreak(10);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.setTextColor(31, 41, 55);
    doc.text(name, margin, y);

    doc.setFont('helvetica', 'bold');
    doc.setTextColor(107, 114, 128);
    doc.text(`${mod.score}/${mod.maxScore}`, pageWidth - margin - 20, y);

    const barY = y + 2;
    const barWidth = contentWidth - 80;
    const barX = margin + 70;

    doc.setFillColor(229, 231, 235);
    doc.roundedRect(barX, barY, barWidth, 3, 1.5, 1.5, 'F');

    const pct = mod.maxScore > 0 ? mod.score / mod.maxScore : 0;
    const color = pct >= 0.8 ? [34, 197, 94] : pct >= 0.5 ? [245, 158, 11] : [239, 68, 68];
    doc.setFillColor(...color);
    if (pct > 0) {
      doc.roundedRect(barX, barY, barWidth * pct, 3, 1.5, 1.5, 'F');
    }

    y += 9;
  });

  y += 4;
  drawLine();

  // Module details
  moduleConfig.forEach(({ key, name }) => {
    const mod = scoreResults.modules[key];
    if (!mod) return;

    sectionTitle(name);

    mod.checks.forEach(check => {
      checkPageBreak(8);

      const statusText = check.status === 'pass' ? 'PASS'
        : check.status === 'warn' ? 'WARN'
        : check.status === 'na' ? 'N/A'
        : 'FAIL';
      const statusColor = check.status === 'pass' ? [34, 197, 94]
        : check.status === 'warn' ? [245, 158, 11]
        : check.status === 'na' ? [156, 163, 175]
        : [239, 68, 68];

      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(...statusColor);
      doc.text(statusText, margin, y);

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(31, 41, 55);
      doc.text(check.name, margin + 18, y);

      if (check.detail) {
        doc.setTextColor(107, 114, 128);
        const detailX = margin + 18 + doc.getTextWidth(check.name) + 4;
        const availableWidth = pageWidth - margin - detailX;
        if (availableWidth > 20) {
          doc.text(truncateStr(check.detail, Math.floor(availableWidth / 1.8)), detailX, y);
        }
      }

      y += 5;
    });

    y += 2;
    drawLine();
  });

  // Footer
  checkPageBreak(20);
  y += 8;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(156, 163, 175);
  doc.text('Generated by TechSEO Inspector', margin, y);
  y += 4;
  doc.setTextColor(45, 127, 249);
  doc.text('Free SEO audit: https://ivig.dev/?ref=techseo-inspector', margin, y);
  y += 4;
  doc.text('SEO guides: https://ivig.dev/seo-guides/?ref=techseo-inspector', margin, y);

  const filename = `seo-report-${new Date().toISOString().slice(0, 10)}.pdf`;
  doc.save(filename);
}

function truncateStr(str, max) {
  if (!str) return '';
  return str.length > max ? str.slice(0, max - 3) + '...' : str;
}
